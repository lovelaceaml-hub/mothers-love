    IF NOT (auth_result->>'ok')::boolean THEN RETURN auth_result; END IF;
    device_id := NULLIF(payload->>'id', '')::uuid;
    UPDATE mothers_love.devices SET revoked_at = COALESCE(revoked_at, now_value), pairing_code_hash = NULL WHERE id = (payload->>'id')::uuid;
    UPDATE mothers_love.display_sessions AS ds SET revoked_at = now_value WHERE ds.device_id = (payload->>'id')::uuid AND ds.revoked_at IS NULL;
    RETURN jsonb_build_object('ok', true);
  END IF;

  IF action = 'admin_members_list' THEN
    auth_result := mothers_love.ml_authorize(payload, 'owner', true);
    IF NOT (auth_result->>'ok')::boolean THEN RETURN auth_result; END IF;
    SELECT COALESCE(jsonb_agg(jsonb_build_object('id', am.user_id::text, 'role', am.role, 'active', am.active) ORDER BY am.invited_at), '[]'::jsonb) INTO member_items FROM mothers_love.admin_memberships am;
    RETURN jsonb_build_object('ok', true, 'items', member_items);
  END IF;

  IF action = 'admin_member_patch' THEN
    auth_result := mothers_love.ml_authorize(payload, 'owner', true);
    IF NOT (auth_result->>'ok')::boolean THEN RETURN auth_result; END IF;
    target_id := NULLIF(payload->>'id', '')::uuid;
    PERFORM pg_catalog.pg_advisory_xact_lock(736507174032991021::bigint);
    IF COALESCE((payload->>'active')::boolean, true) = false AND (SELECT role FROM mothers_love.admin_memberships WHERE user_id = target_id) = 'owner' AND (SELECT count(*) FROM mothers_love.admin_memberships WHERE role = 'owner' AND active) <= 1 THEN RETURN jsonb_build_object('ok', false, 'status', 409, 'code', 'LAST_OWNER'); END IF;
    UPDATE mothers_love.admin_memberships SET active = (payload->>'active')::boolean, updated_at = now_value WHERE user_id = target_id;
    RETURN jsonb_build_object('ok', true);
  END IF;

  IF action = 'display_pair' THEN
    rate_result := mothers_love.ml_check_rate(payload);
    IF NOT (rate_result->>'ok')::boolean THEN RETURN rate_result; END IF;
    IF EXISTS (SELECT 1 FROM mothers_love.rate_limits WHERE scope = 'pairing_ip' AND key_hash = mothers_love.ml_hash(payload->>'rateIp') AND window_start = date_trunc('minute', now_value) AND count >= 5) THEN RETURN jsonb_build_object('ok', false, 'status', 429, 'code', 'THROTTLED'); END IF;
    INSERT INTO mothers_love.rate_limits(scope, key_hash, window_start, count, expires_at) VALUES ('pairing_ip', mothers_love.ml_hash(payload->>'rateIp'), date_trunc('minute', now_value), 1, now_value + interval '24 hours') ON CONFLICT (scope, key_hash, window_start) DO UPDATE SET count = rate_limits.count + 1;
    code_hash := mothers_love.ml_hash(payload->>'code');
    SELECT * INTO device_row FROM mothers_love.devices d WHERE d.pairing_code_hash = code_hash AND d.pairing_code_expires_at > now_value AND d.revoked_at IS NULL FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('ok', false, 'status', 401, 'code', 'INVALID_PAIRING'); END IF;
    token_hash := NULLIF(payload->>'tokenHash', '');
    IF token_hash IS NULL THEN RETURN jsonb_build_object('ok', false, 'status', 400, 'code', 'INVALID_REQUEST'); END IF;
    UPDATE mothers_love.devices SET paired_at = now_value, pairing_code_hash = NULL, pairing_code_expires_at = NULL, pairing_attempts = 0 WHERE id = device_row.id;
    INSERT INTO mothers_love.display_sessions (device_id, token_hash, expires_at) VALUES (device_row.id, token_hash, now_value + interval '30 days');
    RETURN jsonb_build_object('ok', true, 'paired', true);
  END IF;

  IF action = 'display_snapshot' THEN
    token_hash := NULLIF(payload->>'tokenHash', '');
    SELECT d.* INTO device_row
    FROM mothers_love.display_sessions ds
    JOIN mothers_love.devices d ON d.id = ds.device_id
    WHERE ds.token_hash = NULLIF(payload->>'tokenHash', '')
    FOR UPDATE OF d;
    IF NOT FOUND OR device_row.revoked_at IS NOT NULL THEN RETURN jsonb_build_object('ok', false, 'status', 401, 'code', 'UNAUTHENTICATED'); END IF;
    SELECT ds.* INTO session_row FROM mothers_love.display_sessions ds WHERE ds.token_hash = NULLIF(payload->>'tokenHash', '') FOR UPDATE;
    IF NOT FOUND OR session_row.revoked_at IS NOT NULL OR session_row.expires_at <= now_value THEN RETURN jsonb_build_object('ok', false, 'status', 401, 'code', 'UNAUTHENTICATED'); END IF;
    UPDATE mothers_love.display_sessions SET expires_at = LEAST(expires_at, now_value + interval '30 days') WHERE id = session_row.id;
    UPDATE mothers_love.devices SET last_seen_at = now_value WHERE id = device_row.id;
    SELECT COALESCE(max(event_id), 0) INTO latest_event FROM mothers_love.display_events WHERE created_at <= now_value;
    snapshot_revision := GREATEST(latest_event, (SELECT version FROM mothers_love.settings WHERE singleton_id = true));
    IF NULLIF(payload->>'after', '') IS NULL OR (payload->>'after') !~ '^\d+\.\d+$' THEN sync_value := 'reset'; arrivals := '[]'::jsonb;
    ELSE
      cursor_value := split_part(payload->>'after', '.', 1)::bigint;
      cursor_epoch := split_part(payload->>'after', '.', 2)::bigint;
      IF cursor_value < 0 OR cursor_value > latest_event OR cursor_epoch < floor(extract(epoch FROM now_value - interval '7 days'))::bigint THEN sync_value := 'reset'; arrivals := '[]'::jsonb;
      ELSE
        sync_value := 'delta';
        SELECT COALESCE(jsonb_agg(jsonb_build_object('eventId', de.event_id::text, 'recognitionId', de.recognition_id::text, 'publishedAt', de.created_at) ORDER BY de.event_id), '[]'::jsonb) INTO arrivals FROM mothers_love.display_events de JOIN mothers_love.recognitions current_rec ON current_rec.id = de.recognition_id WHERE de.event_id > cursor_value AND de.event_id <= latest_event AND de.created_at > now_value - interval '7 days' AND de.event_kind = 'published' AND de.expires_at > now_value AND current_rec.status = 'published' AND current_rec.expires_at > now_value;
      END IF;
    END IF;
    SELECT * INTO settings_row FROM mothers_love.settings WHERE singleton_id = true;
    SELECT COALESCE(jsonb_agg(mothers_love.ml_public_recognition(r) ORDER BY r.first_published_at DESC), '[]'::jsonb) INTO items FROM mothers_love.recognitions r WHERE r.status = 'published' AND r.expires_at > now_value AND settings_row.mode <> 'neutral';
    aggregate := mothers_love.ml_aggregate_json((now_value AT TIME ZONE 'America/Los_Angeles')::date - EXTRACT(day FROM (now_value AT TIME ZONE 'America/Los_Angeles'))::integer + 1, (now_value AT TIME ZONE 'America/Los_Angeles')::date);
    RETURN jsonb_build_object('ok', true, 'serverTime', now_value, 'revision', snapshot_revision, 'recognitions', COALESCE(items, '[]'::jsonb), 'aggregate', aggregate, 'settings', mothers_love.ml_settings_json(), 'submissionUrl', settings_row.submission_url, 'cursor', format('%s.%s', latest_event, floor(extract(epoch FROM now_value))::bigint), 'sync', sync_value, 'arrivals', arrivals);
  END IF;

  IF action = 'display_ack' THEN
    token_hash := NULLIF(payload->>'tokenHash', '');
    SELECT d.* INTO device_row
    FROM mothers_love.display_sessions ds
    JOIN mothers_love.devices d ON d.id = ds.device_id
    WHERE ds.token_hash = NULLIF(payload->>'tokenHash', '')
    FOR UPDATE OF d;
    IF NOT FOUND OR device_row.revoked_at IS NOT NULL THEN RETURN jsonb_build_object('ok', false, 'status', 401, 'code', 'UNAUTHENTICATED'); END IF;
    SELECT ds.* INTO session_row FROM mothers_love.display_sessions ds WHERE ds.token_hash = NULLIF(payload->>'tokenHash', '') FOR UPDATE;
    IF NOT FOUND OR session_row.revoked_at IS NOT NULL OR session_row.expires_at <= now_value THEN RETURN jsonb_build_object('ok', false, 'status', 401, 'code', 'UNAUTHENTICATED'); END IF;
    device_id := device_row.id;
    UPDATE mothers_love.display_sessions SET expires_at = LEAST(expires_at, now_value + interval '30 days') WHERE id = session_row.id;
    UPDATE mothers_love.devices SET applied_settings_version = GREATEST(applied_settings_version, COALESCE((payload->>'settingsVersion')::bigint, 0)), applied_snapshot_revision = GREATEST(applied_snapshot_revision, COALESCE((payload->>'snapshotRevision')::bigint, 0)), last_seen_at = now_value WHERE id = device_id AND revoked_at IS NULL;
    RETURN jsonb_build_object('ok', true);
  END IF;

  RETURN jsonb_build_object('ok', false, 'status', 404, 'code', 'NOT_FOUND');
EXCEPTION WHEN others THEN
  RETURN jsonb_build_object('ok', false, 'status', 500, 'code', 'DATABASE_ERROR');
END
$function$;

CREATE OR REPLACE FUNCTION mothers_love.purge_expired()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER VOLATILE SET search_path = '' AS $function$
DECLARE
  removed integer;
  now_value timestamptz := clock_timestamp();
BEGIN
  UPDATE mothers_love.admin_audit aa SET target_id = NULL WHERE aa.target_id IN (SELECT r.id FROM mothers_love.recognitions r WHERE r.expires_at <= now_value);
  DELETE FROM mothers_love.recognitions WHERE expires_at <= now_value;
  GET DIAGNOSTICS removed = ROW_COUNT;
  DELETE FROM mothers_love.idempotency_keys WHERE expires_at <= now_value;
  DELETE FROM mothers_love.display_events WHERE expires_at IS NOT NULL AND expires_at <= now_value;
  DELETE FROM mothers_love.rate_limits WHERE expires_at <= now_value;
  DELETE FROM mothers_love.campaign_invitations WHERE expires_at <= now_value OR used_at <= now_value - interval '30 days';
  DELETE FROM mothers_love.admin_audit WHERE expires_at <= now_value;
  UPDATE mothers_love.settings SET last_cleanup_at = now_value, overdue_purge_count = 0, updated_at = now_value WHERE singleton_id = true;
  RETURN jsonb_build_object('ok', true, 'removed', removed, 'at', now_value);
END
$function$;

CREATE OR REPLACE FUNCTION public.ml_purge()
RETURNS jsonb LANGUAGE sql SECURITY DEFINER VOLATILE SET search_path = '' AS $$
  SELECT mothers_love.purge_expired()
$$;

