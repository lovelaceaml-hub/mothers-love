CREATE OR REPLACE FUNCTION mothers_love.ml_apply_delta(p_period_start date, p_delta integer[], p_recognition_delta integer)
RETURNS void LANGUAGE plpgsql VOLATILE SET search_path = '' AS $function$
BEGIN
  INSERT INTO mothers_love.daily_aggregates (period_start, period_end)
  VALUES (p_period_start, p_period_start)
  ON CONFLICT (period_start) DO NOTHING;
  UPDATE mothers_love.daily_aggregates
  SET recognitions = recognitions + p_recognition_delta,
      expression_counts = ARRAY[
        expression_counts[1] + COALESCE(p_delta[2], 0),
        expression_counts[2] + COALESCE(p_delta[3], 0),
        expression_counts[3] + COALESCE(p_delta[4], 0),
        expression_counts[4] + COALESCE(p_delta[5], 0),
        expression_counts[5] + COALESCE(p_delta[6], 0),
        expression_counts[6] + COALESCE(p_delta[7], 0),
        expression_counts[7] + COALESCE(p_delta[8], 0),
        expression_counts[8] + COALESCE(p_delta[9], 0),
        expression_counts[9] + COALESCE(p_delta[10], 0)
      ],
      expression_total = expression_total + COALESCE(p_delta[2], 0) + COALESCE(p_delta[3], 0) + COALESCE(p_delta[4], 0) + COALESCE(p_delta[5], 0) + COALESCE(p_delta[6], 0) + COALESCE(p_delta[7], 0) + COALESCE(p_delta[8], 0) + COALESCE(p_delta[9], 0) + COALESCE(p_delta[10], 0),
      revision = revision + 1,
      updated_at = now()
  WHERE mothers_love.daily_aggregates.period_start = p_period_start;
  IF EXISTS (SELECT 1 FROM mothers_love.daily_aggregates WHERE mothers_love.daily_aggregates.period_start = p_period_start AND (recognitions < 0 OR expression_total < 0 OR expression_counts[1] < 0 OR expression_counts[2] < 0 OR expression_counts[3] < 0 OR expression_counts[4] < 0 OR expression_counts[5] < 0 OR expression_counts[6] < 0 OR expression_counts[7] < 0 OR expression_counts[8] < 0 OR expression_counts[9] < 0)) THEN
    RAISE EXCEPTION 'aggregate underflow';
  END IF;
END
$function$;

CREATE OR REPLACE FUNCTION mothers_love.ml_aggregate_json(period_from date, period_to date)
RETURNS jsonb LANGUAGE plpgsql STABLE SET search_path = '' AS $function$
DECLARE
  counts integer[];
  recognition_count integer;
  expression_count integer;
  aggregate_revision bigint;
BEGIN
  SELECT COALESCE(sum(da.recognitions), 0)::integer,
         COALESCE(sum(da.expression_total), 0)::integer,
         COALESCE(max(da.revision), 0)::bigint,
         ARRAY[
           COALESCE(sum(da.expression_counts[1]), 0)::integer,
           COALESCE(sum(da.expression_counts[2]), 0)::integer,
           COALESCE(sum(da.expression_counts[3]), 0)::integer,
           COALESCE(sum(da.expression_counts[4]), 0)::integer,
           COALESCE(sum(da.expression_counts[5]), 0)::integer,
           COALESCE(sum(da.expression_counts[6]), 0)::integer,
           COALESCE(sum(da.expression_counts[7]), 0)::integer,
           COALESCE(sum(da.expression_counts[8]), 0)::integer,
           COALESCE(sum(da.expression_counts[9]), 0)::integer
         ]
  INTO recognition_count, expression_count, aggregate_revision, counts
  FROM mothers_love.daily_aggregates da
  WHERE da.period_start BETWEEN period_from AND period_to;
  RETURN jsonb_build_object('periodStart', period_from, 'periodEnd', period_to, 'recognitions', recognition_count, 'expressionCounts', to_jsonb(counts), 'expressionTotal', expression_count, 'revision', aggregate_revision);
END
$function$;

CREATE OR REPLACE FUNCTION mothers_love.ml_authorize(payload jsonb, minimum_role text DEFAULT 'moderator', require_aal2 boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql STABLE SET search_path = '' AS $function$
DECLARE
  actor_id uuid;
  actor_role text;
  actor_aal2 boolean;
BEGIN
  IF COALESCE(payload #>> '{actor,userId}', '') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
    RETURN jsonb_build_object('ok', false, 'status', 401, 'code', 'UNAUTHENTICATED');
  END IF;
  actor_id := (payload #>> '{actor,userId}')::uuid;
  actor_aal2 := COALESCE(payload #>> '{actor,aal2}', '') = 'true';
  SELECT am.role INTO actor_role FROM mothers_love.admin_memberships am WHERE am.user_id = actor_id AND am.active;
  IF actor_role IS NULL THEN RETURN jsonb_build_object('ok', false, 'status', 403, 'code', 'FORBIDDEN'); END IF;
  IF minimum_role = 'owner' AND actor_role <> 'owner' THEN RETURN jsonb_build_object('ok', false, 'status', 403, 'code', 'OWNER_REQUIRED'); END IF;
  IF require_aal2 AND actor_role = 'owner' AND NOT actor_aal2 THEN RETURN jsonb_build_object('ok', false, 'status', 403, 'code', 'MFA_REQUIRED'); END IF;
  RETURN jsonb_build_object('ok', true, 'userId', actor_id::text, 'role', actor_role, 'aal2', actor_aal2);
END
$function$;

CREATE OR REPLACE FUNCTION mothers_love.ml_check_rate(payload jsonb)
RETURNS jsonb LANGUAGE plpgsql VOLATILE SET search_path = '' AS $function$
DECLARE
  now_minute timestamptz := date_trunc('minute', now());
  ip_hash text := mothers_love.ml_hash(payload->>'rateIp');
  context_hash text := mothers_love.ml_hash(payload->>'rateContext');
  current_count integer;
BEGIN
  IF COALESCE(payload->>'rateIp', '') = '' THEN RETURN jsonb_build_object('ok', false, 'status', 429, 'code', 'THROTTLED'); END IF;
  INSERT INTO mothers_love.rate_limits(scope, key_hash, window_start, count, expires_at)
  VALUES ('shared_ip', ip_hash, now_minute, 1, now() + interval '24 hours')
  ON CONFLICT (scope, key_hash, window_start) DO UPDATE SET count = rate_limits.count + 1
  RETURNING count INTO current_count;
  IF current_count > 120 THEN RETURN jsonb_build_object('ok', false, 'status', 429, 'code', 'THROTTLED'); END IF;
  IF COALESCE(payload->>'rateContext', '') <> '' THEN
    INSERT INTO mothers_love.rate_limits(scope, key_hash, window_start, count, expires_at)
    VALUES ('browser_context', context_hash, now_minute, 1, now() + interval '24 hours')
    ON CONFLICT (scope, key_hash, window_start) DO UPDATE SET count = rate_limits.count + 1
    RETURNING count INTO current_count;
    IF current_count > 10 THEN RETURN jsonb_build_object('ok', false, 'status', 429, 'code', 'THROTTLED'); END IF;
  END IF;
  RETURN jsonb_build_object('ok', true);
END
$function$;

CREATE OR REPLACE FUNCTION public.ml_api(action text, payload jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  settings_row mothers_love.settings%ROWTYPE;
  rec mothers_love.recognitions%ROWTYPE;
  old_contribution integer[];
  new_contribution integer[];
  delta integer[];
  period_start date;
  result jsonb;
  auth_result jsonb;
  rate_result jsonb;
  req_key text;
  existing_id uuid;
  existing_hash text;
  new_id uuid;
  now_value timestamptz := clock_timestamp();
  expires_value timestamptz;
  hold boolean;
  hold_reason text;
  filter_categories jsonb;
  expected_version integer;
  page_number integer;
  page_size integer;
  total_count integer;
  items jsonb;
  search_value text;
  expression_filter integer;
  status_filter text;
  from_value date;
  to_value date;
  target_id uuid;
  fields jsonb;
  effective_ids jsonb;
  mutation_action text;
  reason_value text;
  role_value text;
  email_value text;
  email_hash text;
  device_id uuid;
  token_hash text;
  cursor_value bigint;
  cursor_epoch bigint;
  latest_event bigint;
  sync_value text;
  arrivals jsonb;
  snapshot_revision bigint;
  device_row mothers_love.devices%ROWTYPE;
  session_row mothers_love.display_sessions%ROWTYPE;
  setting_changes jsonb;
  device_items jsonb;
  member_items jsonb;
  aggregate jsonb;
  label_value text;
  code_hash text;
BEGIN
  IF action = 'config' THEN
    SELECT * INTO settings_row FROM mothers_love.settings WHERE singleton_id = true;
    RETURN jsonb_build_object('ok', true, 'collectionOpen', COALESCE(settings_row.collection_open, false) AND mothers_love.ml_purge_healthy(now_value));
  END IF;

  IF action = 'submit' THEN
    rate_result := mothers_love.ml_check_rate(payload);
    IF NOT (rate_result->>'ok')::boolean THEN RETURN rate_result; END IF;
    SELECT * INTO settings_row FROM mothers_love.settings WHERE singleton_id = true;
    IF NOT COALESCE(settings_row.collection_open, false) OR NOT mothers_love.ml_purge_healthy(now_value) THEN RETURN jsonb_build_object('ok', false, 'status', 503, 'code', 'UNAVAILABLE'); END IF;
    req_key := NULLIF(payload->>'requestKey', '');
    IF req_key IS NULL THEN RETURN jsonb_build_object('ok', false, 'status', 400, 'code', 'INVALID_REQUEST'); END IF;
    PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(req_key, 3987123456::bigint));
    DELETE FROM mothers_love.idempotency_keys WHERE expires_at <= now_value;
    SELECT ik.recognition_id, ik.accepted_status, ik.payload_hash INTO existing_id, role_value, existing_hash FROM mothers_love.idempotency_keys ik WHERE ik.request_key = req_key AND ik.expires_at > now_value;
    IF existing_id IS NOT NULL THEN
      IF existing_hash IS DISTINCT FROM COALESCE(payload->>'payloadHash', '') THEN RETURN jsonb_build_object('ok', false, 'status', 409, 'code', 'IDEMPOTENCY_CONFLICT'); END IF;
      SELECT * INTO rec FROM mothers_love.recognitions WHERE id = existing_id AND expires_at > now_value;
      IF FOUND THEN RETURN jsonb_build_object('ok', true, 'id', rec.id::text, 'status', role_value, 'expiresAt', rec.expires_at); END IF;
      DELETE FROM mothers_love.idempotency_keys AS old_key WHERE old_key.request_key = req_key;
    END IF;
    hold := COALESCE((payload->>'hold')::boolean, false);
    filter_categories := COALESCE(payload->'filterCategories', '[]'::jsonb);
    hold_reason := CASE WHEN hold AND filter_categories ? 'filter_error' THEN 'filter_error' WHEN hold THEN 'safety' ELSE NULL END;
    expires_value := now_value + interval '168 hours';
    INSERT INTO mothers_love.recognitions (submitted_name, recipient, message, status, reason_category, created_at, first_published_at, expires_at)
    VALUES (payload->>'submittedName', payload->>'recipient', payload->>'message', CASE WHEN hold THEN 'held' ELSE 'published' END, hold_reason, now_value, CASE WHEN hold THEN NULL ELSE now_value END, expires_value)
    RETURNING * INTO rec;
    new_id := rec.id;
    INSERT INTO mothers_love.idempotency_keys (request_key, recognition_id, payload_hash, accepted_status, expires_at)
    VALUES (req_key, new_id, COALESCE(payload->>'payloadHash', ''), CASE WHEN hold THEN 'held' ELSE 'published' END, expires_value)
    ON CONFLICT (request_key) DO NOTHING;
