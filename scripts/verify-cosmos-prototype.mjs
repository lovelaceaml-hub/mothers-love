import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const origin=process.env.COSMOS_ORIGIN||'http://127.0.0.1:32861';
const output=process.env.COSMOS_OUTPUT||'/private/tmp/mothers-love-pearl-sequence/browser';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=metal']});
const context=await browser.newContext({viewport:{width:1920,height:1080},deviceScaleFactor:1,reducedMotion:'reduce'});
const page=await context.newPage();
const report={origin,browser:browser.version(),checks:[],errors:[],apiRequests:[],failedRequests:[]};
page.on('pageerror',e=>report.errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')report.errors.push(m.text());});
page.on('requestfailed',r=>report.failedRequests.push({url:r.url(),error:r.failure()?.errorText}));
await page.route('**/api/**',route=>{report.apiRequests.push(new URL(route.request().url()).pathname);return route.abort();});
const world=page.getByTestId('world-preview');
const attrs=()=>world.evaluate(el=>Object.fromEntries([...el.attributes].filter(a=>a.name.startsWith('data-')).map(a=>[a.name,a.value])));
async function shot(name){await page.screenshot({path:path.join(output,name+'.png')});}
try{
  await page.goto(origin+'/display/cosmos-prototype?source=live',{waitUntil:'domcontentloaded'});
  await expect(world).toHaveAttribute('data-ready','true',{timeout:60000});
  await expect(world).toHaveAttribute('data-prototype-scenery-ready','true',{timeout:60000});
  await expect(world).toHaveAttribute('data-source','sample');
  await expect(world).toHaveAttribute('data-zone','orbit');
  await expect.poll(async()=>Number(await world.getAttribute('data-frames'))).toBeGreaterThan(0);
  await expect(world).toHaveAttribute('data-world-bubbles','3');
  report.checks.push({test:'Authored scenery renders with three fictional pearls even for source=live',passed:true,attributes:await attrs()});
  await page.getByRole('button',{name:'Pause tour',exact:true}).click();
  await shot('cosmos-hd');
  const before=await attrs();await page.waitForTimeout(1100);const after=await attrs();
  report.checks.push({test:'Paused scene freezes camera and scene time',passed:before['data-camera-position']===after['data-camera-position']&&before['data-elapsed']===after['data-elapsed']});
  await page.getByRole('button',{name:'Read recognitions',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Thank you for noticing I needed a hand');
  await page.getByRole('dialog').getByRole('button',{name:/^Close /}).click();
  report.checks.push({test:'Complete fictional recognition remains accessible',passed:true});
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await expect(page.getByLabel('Content',{exact:true})).toBeDisabled();
  await page.getByText('Rendering details',{exact:true}).click();
  report.rendering=await page.getByRole('dialog').locator('dl').innerText();
  await page.getByRole('dialog').getByRole('button',{name:/^Close /}).click();
  await page.setViewportSize({width:3840,height:2160});
  await expect.poll(()=>page.locator('canvas[role="img"]').evaluate(c=>`${c.width}x${c.height}`)).toBe('3840x2160');
  await shot('cosmos-4k');
  report.checks.push({test:'Native 4K drawing buffer',passed:true});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(500);await shot('cosmos-phone');
  report.checks.push({test:'Phone has no horizontal page overflow',passed:await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)});
  report.checks.push({test:'Phone title is above the pearl',passed:(await page.getByRole('heading',{name:'Expression Cosmos',exact:true}).boundingBox()).y<200});
  await page.setViewportSize({width:1920,height:1080});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.getByRole('button',{name:'Resume tour',exact:true}).click();
  const movingBefore=await attrs();await page.waitForTimeout(6000);const movingAfter=await attrs();
  report.checks.push({test:'Real app clock and gentle camera advance',passed:Number(movingAfter['data-elapsed'])>Number(movingBefore['data-elapsed'])+3&&movingAfter['data-camera-position']!==movingBefore['data-camera-position'],before:movingBefore,after:movingAfter});
  const driftX=Number(movingAfter['data-world-bubble-position'].split(',')[0])-Number(movingBefore['data-world-bubble-position'].split(',')[0]);
  report.checks.push({test:'The pearl visibly floats through the world',passed:Math.abs(driftX)>1.5,worldDistanceX:driftX});
  await shot('cosmos-floating');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByText('Rendering details',{exact:true}).click();
  report.motionRendering=await page.getByRole('dialog').locator('dl').innerText();
  await page.getByRole('dialog').getByRole('button',{name:/^Close /}).click();
  await page.getByRole('button',{name:'Hold this recognition',exact:true}).click();
  await expect(page.getByRole('button',{name:'Continue reading tour',exact:true})).toHaveAttribute('aria-pressed','true');
  // Engine diagnostics publish once per second. Wait for a fresh post-click report.
  const frameAtHold=Number(await world.getAttribute('data-frames'));
  await expect.poll(async()=>Number(await world.getAttribute('data-frames'))).toBeGreaterThan(frameAtHold);
  const heldBefore=await attrs();await page.waitForTimeout(1100);const heldAfter=await attrs();
  report.checks.push({test:'Holding preserves the reading position',passed:heldBefore['data-reading-remaining']===heldAfter['data-reading-remaining'],before:heldBefore['data-reading-remaining'],after:heldAfter['data-reading-remaining']});
  report.checks.push({test:'Hold also freezes the floating pearl and effects',passed:heldBefore['data-world-bubble-position']===heldAfter['data-world-bubble-position']&&heldBefore['data-elapsed']===heldAfter['data-elapsed']});
  await page.getByRole('button',{name:'Continue reading tour',exact:true}).click();
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(world).toHaveAttribute('data-motion','still');
  await page.waitForTimeout(300);
  const reducedBefore=await attrs();await page.waitForTimeout(1200);const reducedAfter=await attrs();
  report.checks.push({test:'Reduced motion stops visual scene time',passed:reducedBefore['data-elapsed']===reducedAfter['data-elapsed']});
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button',{name:'Settings',exact:true})).toBeFocused();
  report.checks.push({test:'Escape closes the dialog and restores keyboard focus',passed:true});
  await page.locator('canvas[role="img"]').evaluate(canvas=>canvas.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext());
  await expect(page.getByRole('button',{name:'Try 3D again',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Read recognitions',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Thank you for noticing I needed a hand');
  report.checks.push({test:'Lost graphics context retains the full fictional reader and retry control',passed:true});
}catch(error){report.checks.push({test:'Prototype journey',passed:false,error:String(error)});await shot('failure').catch(()=>{});}
finally{
  report.checks.push({test:'No API calls or browser errors',passed:report.apiRequests.length===0&&report.errors.length===0});
  await context.close();await browser.close();
  await writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
}
if(report.checks.some(c=>!c.passed))process.exitCode=1;
