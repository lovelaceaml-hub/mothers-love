import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
const original = readFileSync('prototypes/tv-v6/Mothers_Love_TV_Prototype_v6.html', 'utf8');
const hash = createHash('sha256').update(original).digest('hex');
if (hash !== '9fd625cea86eebd6d8cf342b375cb86b65bb9466ec49726d55e208f78707d45e') throw new Error('V6 source changed. Review it before recoloring.');
const start = original.indexOf('const catalog='), end = original.indexOf('const seed=', start);
if(start<0 || end<0) throw new Error('Expected V6 catalog not found');
const colors=['#FF977C','#FFD05F','#FFAD69','#F582AF','#82B0ED','#CE927E','#B293E7','#EF7A96','#BE9CEB'];
let i=0;
const catalog = original.slice(start,end).replace(/color:'#[0-9a-fA-F]{6}'/g,()=>`color:'${colors[i++]}'`);
if(i!==9) throw new Error('Expected exactly nine color values');
const css=readFileSync('prototypes/tv-v6/color-polish.css','utf8');
let result=original.slice(0,start)+catalog+original.slice(end);
result=result.replace('</head>',`<style id="color-polish">${css}</style></head>`);
mkdirSync('color-review-evidence',{recursive:true});
writeFileSync('color-review-evidence/Mothers_Love_TV_Color_Polish.html',result);
const strip=s=>s.match(/<script>[\s\S]*?<\/script>/g).join('').replace(/color:'#[0-9a-fA-F]{6}'/g,"color:'COLOR'");
if(strip(original)!==strip(result)) throw new Error('Non-color executable change detected');
writeFileSync('color-review-evidence/prototype-boundary.json',JSON.stringify({sourceSha256:hash,outputSha256:createHash('sha256').update(result).digest('hex'),colorValuesChanged:i,otherExecutableChanges:0},null,2));
console.log('Built color-only V6; original source and behavior preserved.');
